import * as React from "react";
import { cn } from "@/utils/cn";

const Card = React.forwardRef<
  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement> & {
    hover?: boolean;
    tier?: "content" | "work";
  }
>(({ className, hover = false, tier = "content", ...props }, ref) => (
  <div
    data-glass={tier}
    ref={ref}
    className={cn(
      "sf-card rounded-xl border border-white/70 bg-white/75 backdrop-blur-xl text-card-foreground shadow-[0_8px_32px_rgba(249,115,22,0.08)]",
      hover &&
        "transition-all duration-300 hover:shadow-medium hover:-translate-y-1",
      className,
    )}
    {...props}
  />
));
Card.displayName = "Card";

